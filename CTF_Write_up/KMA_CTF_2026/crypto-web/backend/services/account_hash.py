def _gf_reduce(value: int) -> int:
    while value.bit_length() > _GF_BITS:
        value ^= _GF_POLY << (value.bit_length() - _GF_BITS - 1)
    return value


def _gf_mul(a: int, b: int) -> int:
    out = 0
    while b:
        if b & 1:
            out ^= a
        b >>= 1
        a <<= 1
        if a >> _GF_BITS:
            a ^= _GF_POLY
    return _gf_reduce(out)


def _matrix_mul(left: tuple[int, int, int, int], right: tuple[int, int, int, int]) -> tuple[int, int, int, int]:
    a, b, c, d = left
    e, f, g, h = right
    return (
        _gf_mul(a, e) ^ _gf_mul(b, g),
        _gf_mul(a, f) ^ _gf_mul(b, h),
        _gf_mul(c, e) ^ _gf_mul(d, g),
        _gf_mul(c, f) ^ _gf_mul(d, h),
    )


def _scramble_matrix_bits(segment: bytes) -> list[int]:
    if len(segment) != _MATRIX_INPUT_BYTES:
        raise ValueError("bad matrix segment length")

    value = int.from_bytes(segment, "big")
    bits = [
        (value >> (_MATRIX_INPUT_BITS - 1 - i)) & 1
        for i in range(_MATRIX_INPUT_BITS)
    ]
    return [
        bits[_BIT_PERMUTATION[i]] ^ ((_BIT_MASK >> (_MATRIX_INPUT_BITS - 1 - i)) & 1)
        for i in range(_MATRIX_INPUT_BITS)
    ]


def _matrix_digest(segment: bytes) -> tuple[int, int, int, int]:
    stream = _scramble_matrix_bits(segment)
    state = _INITIAL_MATRIX

    for i in range(0, _MATRIX_INPUT_BITS, 4):
        step = (stream[i] << 3) | (stream[i + 1] << 2) | (stream[i + 2] << 1) | stream[i + 3]
        state = _matrix_mul(state, _MATRIX_TABLE[step])

    return state


def _pack_matrix(state: tuple[int, int, int, int]) -> bytes:
    return b"".join(value.to_bytes(_GF_BYTES, "big") for value in state)


def account_route_digest(account_id: int) -> bytes:
    if not (0 <= account_id < ACCOUNT_ID_MAX):
        raise ValueError("invalid account_id")

    raw = account_id.to_bytes(ACCOUNT_ID_BYTES, "big")
    return _pack_matrix(_matrix_digest(raw))


def hash_function(account_id: int) -> bytes:
    return account_route_digest(account_id)
